import { NextRequest, NextResponse } from "next/server";
import { getSupabaseAdmin } from "@/lib/supabase";

export async function PATCH(
  request: NextRequest,
  { params }: { params: Promise<{ id: string }> }
) {
  try {
    const supabase = getSupabaseAdmin();
    const { id } = await params;
    const body = await request.json();

    const { title, description, tags, status, scheduled_at } = body;

    // Fetch existing video record first
    const { data: existingVideo, error: fetchErr } = await supabase
      .from("videos")
      .select("*")
      .eq("id", id)
      .single();

    if (fetchErr || !existingVideo) {
      return NextResponse.json(
        { error: `Video #${id} not found` },
        { status: 404 }
      );
    }

    const updates: Record<string, any> = {
      updated_at: new Date().toISOString(),
    };

    if (title !== undefined) updates.title = title;
    if (description !== undefined) updates.description = description;
    if (tags !== undefined) {
      updates.tags = Array.isArray(tags) ? tags.join(",") : tags;
    }

    if (status) {
      if (status === "regenerate") {
        // 1. Add back into ideas table for re-generation
        const topic = title || existingVideo.title;
        await supabase.from("ideas").insert({
          topic,
        });

        // 2. Mark this particular video run as rejected/superseded
        updates.status = "rejected";
        updates.error_log = "Regenerated by reviewer";
      } else if (status === "approved") {
        updates.status = "approved";
        if (scheduled_at) {
          updates.scheduled_publish_at = scheduled_at;
          updates.scheduled_at = scheduled_at;
        }
      } else {
        updates.status = status;
      }
    }

    const { data: updatedVideo, error: updateErr } = await supabase
      .from("videos")
      .update(updates)
      .eq("id", id)
      .select()
      .single();

    if (updateErr) {
      return NextResponse.json({ error: updateErr.message }, { status: 500 });
    }

    return NextResponse.json({ video: updatedVideo });
  } catch (err: any) {
    return NextResponse.json(
      { error: err.message || "Failed to update video" },
      { status: 500 }
    );
  }
}
